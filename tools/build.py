"""
build.py - builds WarzoneVB with the Visual Basic 6 command line compiler:
four ActiveX DLLs, then Warzone.exe, into bin/.

  python -I tools\\build.py [--release] [--break-compat NAME] [--unregister]

* each project is a folder in src/ (see PROJECTS); a folder without sources is
  skipped, and so are references to it
* writes each project's .vbp from the .bas, .cls and .frm files in its folder,
  normalised to CRLF line endings (VB6 requires them)
* the DLLs build with binary compatibility against their copy in compat/, so
  their class and type library GUIDs stay the same from build to build; the
  first build makes that copy, and a build whose interface grew (a new type
  library version) refreshes it, or VB would give the new members fresh GUIDs
  on every build. --break-compat NAME drops it, for a change to NAME's public
  interface that VB6 refuses as incompatible
* references between projects come from the built DLLs' type libraries
  (tools/typelib.py), not from the registry
* the .vbp files name bin/, compat/ and build/ by paths relative to
  themselves, so any copy of the tree opens and builds in VB6: it finds an
  unregistered DLL's type library at the Reference= path
* Warzone.exe gets an embedded reg-free COM manifest naming every DLL class
  (build/Warzone.exe.manifest -> build/Warzone.res), so bin/ runs without
  regsvr32. VB6 itself registers each DLL it builds; --unregister undoes that
  afterwards (bin/ still runs)
* VB6 reports only the first error, with the file and line. An empty log
  means VB6 stopped without a message: usually the project's name table is
  full (about 32,100 names, see docs/PLAN.md and tools/name_budget.py)

* makes data/ a directory junction to ref/warzone2100/data when there is no
  data/ yet: Warzone looks for its data in <prefix>/data, the prefix being
  the folder above bin/ (scanDataDirs), as in an installed game. Remove the
  junction with "rmdir data" (cmd), which leaves its target alone

--release removes the array bounds checks.
WzSound is always optimised for fast code without bounds checks (OPTIMISED: its decoder
and mixer are pure arithmetic, and the game's state does not depend on them); the
other projects are compiled without optimisation (docs/PLAN.md, "Speed").
"""
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import typelib  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VB6 = r"C:\Program Files (x86)\Microsoft Visual Studio\VB98\VB6.EXE"
RC = r"C:\Program Files (x86)\Microsoft Visual Studio\VB98\Wizards\RC.EXE"
SRC = os.path.join(ROOT, "src")
BIN = os.path.join(ROOT, "bin")
COMPAT = os.path.join(ROOT, "compat")
BUILD = os.path.join(ROOT, "build")

# name, kind, folder in src/, referenced projects (built before it)
PROJECTS = [
    ("WzFramework", "dll", "framework", []),
    ("WzMap", "dll", "map", ["WzFramework"]),
    ("WzSound", "dll", "sound", ["WzFramework"]),
    ("WzGfx", "dll", "gfx", ["WzFramework"]),
    ("WzNet", "dll", "net", ["WzFramework"]),
    ("WzPlatform", "dll", "platform", ["WzFramework", "WzGfx"]),
    ("Warzone", "exe", "game", ["WzFramework", "WzMap", "WzSound", "WzGfx", "WzNet", "WzPlatform"]),
]
# Projects optimised for fast code, without array bounds checks (the module docstring)
OPTIMISED = {"WzSound"}
# Compiled into every project, like a static C runtime: the C library replacements and
# small framework modules without state (docs/CONVENTIONS.md, "Structure")
SHARED = os.path.join(SRC, "shared")
# Compiled into the projects that draw (WzGfx and the exe): glm's types and gfx_api.h's constant
# buffers and vertex structs, which both sides fill and read (docs/CONVENTIONS.md, "The renderer")
SHARED_GFX = os.path.join(SHARED, "gfx")
SHARED_GFX_USERS = ("gfx", "game")
REF =os.path.join(ROOT, "ref", "warzone2100")

AUTOREVISION = '''Attribute VB_Name = "autorevision_vb"
' Generated by tools/build.py from the git checkout in ref/warzone2100 (Warzone
' generates build_tools/autorevision.h the same way), with the build date
' (C: __DATE__, as i18n.cpp's getCompileDate formats it). Do not edit.
Option Explicit

Public Const VCS_TYPE As String = "git"
Public Const VCS_BASENAME As String = "warzone2100"
Public Const VCS_BRANCH As String = "{branch}"
Public Const VCS_TAG As String = "{tag}"
Public Const VCS_EXTRA As String = "{extra}"
Public Const VCS_FULL_HASH As String = "{full}"
Public Const VCS_SHORT_HASH As String = "{short}"
Public Const VCS_WC_MODIFIED As Long = {modified}
Public Const VCS_MOST_RECENT_TAGGED_VERSION As String = "{recent}"
Public Const BUILD_DATE As String = "{date}"
'''


def git(*args):
    r = subprocess.run(["git", "-C", REF] + list(args), capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def write_autorevision():
    """src/shared/autorevision_vb.bas, rewritten only when its contents change."""
    import datetime
    tag = git("describe", "--exact-match", "--tags")
    text = AUTOREVISION.format(
        branch="" if tag else git("rev-parse", "--abbrev-ref", "HEAD").replace("HEAD", ""),
        tag=tag, extra="" if tag else git("describe", "--tags", "--always"),
        full=git("rev-parse", "HEAD"), short=git("rev-parse", "--short=7", "HEAD"),
        modified=1 if git("status", "--porcelain", "--untracked-files=no") else 0,
        recent=git("describe", "--tags", "--abbrev=0"),
        date=datetime.date.today().isoformat()).replace("\n", "\r\n")
    path = os.path.join(SHARED, "autorevision_vb.bas")
    old = open(path, "rb").read().decode("latin-1") if os.path.exists(path) else ""
    if old != text:
        with open(path, "wb") as f:
            f.write(text.encode("latin-1"))

STDOLE = ("Reference=*\\G{00020430-0000-0000-C000-000000000046}#2.0#0#"
          "C:\\Windows\\SysWOW64\\stdole2.tlb#OLE Automation")
SOURCE_EXT = (".bas", ".cls", ".frm")
LINK_LIMIT = 30000      # VB6 passes every .OBJ path to LINK.EXE on one command line (32,767 at most)

VBP_TAIL = """Startup="{startup}"
HelpFile=""
Title="{name}"
ExeName32="{name}.{ext}"
Path32="{path}"
Command32=""
Name="{name}"
HelpContextID="0"
{compat}MajorVer=1
MinorVer=0
RevisionVer=0
AutoIncrementVer=0
ServerSupportFiles=0
VersionComments="Visual Basic 6 port of Warzone 2100 4.7.0 (GNU GPL v2 or later)"
VersionCompanyName="WarzoneVB"
VersionFileDescription="{name}"
VersionProductName="WarzoneVB"
CompilationType=0
OptimizationType={optimisation}
FavorPentiumPro(tm)=0
CodeViewDebugInfo=0
NoAliasing=0
BoundsCheck={bounds}
OverflowCheck=-1
FlPointCheck=-1
FDIVCheck=-1
UnroundedFP=-1
StartMode=0
Unattended=0
Retained=0
ThreadPerObject=0
MaxNumberOfThreads=1
{threading}"""


def sources(folder):
    if not os.path.isdir(folder):
        return []
    return sorted(n for n in os.listdir(folder) if n.lower().endswith(SOURCE_EXT))


def normalise(path):
    with open(path, "rb") as f:
        data = f.read()
    fixed = data.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
    if fixed != data:
        with open(path, "wb") as f:
            f.write(fixed)


def vb_name(path):
    with open(path, "r", encoding="latin-1") as f:
        for line in f:
            if line.startswith("Attribute VB_Name"):
                return line.split('"')[1]
    return os.path.splitext(os.path.basename(path))[0]


def dll_path(name):
    return os.path.join(BIN, name + ".dll")


def write_vbp(name, kind, folder, refs, release, resfile):
    def relative(path):
        return os.path.relpath(path, folder)

    lines = ["Type=" + ("OleDll" if kind == "dll" else "Exe"), STDOLE]
    for ref in refs:
        libname, tlbid, (major, minor), _ = typelib.library(dll_path(ref))
        lines.append("Reference=*\\G%s#%x.%x#0#%s#%s" % (tlbid, major, minor, relative(dll_path(ref)), libname))
    files = [(n, n) for n in sources(folder)]
    files += [(n, "..\\shared\\" + n) for n in sources(SHARED)]
    if os.path.basename(folder) in SHARED_GFX_USERS:
        files += [(n, "..\\shared\\gfx\\" + n) for n in sources(SHARED_GFX)]
    link_chars = 0
    for n, rel in files:
        path = os.path.normpath(os.path.join(folder, rel))
        normalise(path)
        link_chars += len(os.path.splitext(path)[0]) + 6
        if n.lower().endswith(".frm"):
            lines.append("Form=" + rel)
        elif n.lower().endswith(".cls"):
            lines.append("Class=%s; %s" % (vb_name(path), rel))
        else:
            lines.append("Module=%s; %s" % (vb_name(path), rel))
    if link_chars > LINK_LIMIT:
        print("WARNING: %s: about %d characters of .OBJ paths for LINK.EXE (limit 32,767): "
              "build from a shorter path (subst)" % (name, link_chars))
    if resfile:
        lines.append('ResFile32="%s"' % relative(resfile))
    compat = ""
    if kind == "dll":
        if os.path.exists(os.path.join(COMPAT, name + ".dll")):
            compat = 'CompatibleMode="2"\nCompatibleEXE32="%s"\n' % relative(os.path.join(COMPAT, name + ".dll"))
        else:
            compat = 'CompatibleMode="0"\n'
    lines.append(VBP_TAIL.format(name=name, ext=kind if kind == "dll" else "exe", path=relative(BIN),
                                 startup="(None)" if kind == "dll" else "Sub Main",
                                 compat=compat, bounds="-1" if release or name in OPTIMISED else "0",
                                 optimisation="0" if name in OPTIMISED else "2",
                                 threading="ThreadingModel=1\n" if kind == "dll" else ""))
    vbp = os.path.join(folder, name + ".vbp")
    with open(vbp, "w", newline="\r\n") as f:
        f.write("\n".join(lines))
    return vbp


def make(name, folder, vbp):
    log = os.path.join(BUILD, name + "_build.log")
    if os.path.exists(log):
        os.remove(log)
    subprocess.run([VB6, "/make", vbp, "/outdir", BIN, "/out", log], cwd=folder)
    text = ""
    if os.path.exists(log):
        with open(log, "r", encoding="latin-1") as f:
            text = f.read().strip()
    if not text:
        text = ("%s: VB6 stopped without a message (usually a full name table: "
                "python -I tools\\name_budget.py)" % name)
    print(text)
    return "succeeded" in text


def write_manifest(dlls, exe="Warzone"):
    """The exe's reg-free COM manifest, compiled into build/<exe>.res; returns the .res path."""
    lines = ['<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
             '<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">',
             '  <assemblyIdentity type="win32" name="%s" version="1.0.0.0"/>' % ("WarzoneVB" if exe == "Warzone" else exe)]
    for name in dlls:
        libname, tlbid, (major, minor), classes = typelib.library(dll_path(name))
        lines.append('  <file name="%s.dll">' % name)
        for cname, clsid in classes:
            lines.append('    <comClass clsid="%s" progid="%s.%s" threadingModel="Apartment" tlbid="%s"/>'
                         % (clsid, libname, cname, tlbid))
        # decimal here (the .vbp's Reference= lines take hex): "1.b" is invalid in a manifest
        lines.append('    <typelib tlbid="%s" version="%d.%d" helpdir="" flags=""/>' % (tlbid, major, minor))
        lines.append("  </file>")
    lines.append("</assembly>")
    # The resource ends up rounded to a multiple of 4 bytes with NULs, which Windows rejects as
    # invalid XML ("Activation context generation failed ... Invalid Xml syntax" in the event log,
    # "corrupted shared library" in bash): pad with spaces so there is nothing to round.
    data = ("\r\n".join(lines) + "\r\n").encode("utf-8")
    data += b" " * (-len(data) % 8)
    with open(os.path.join(BUILD, exe + ".exe.manifest"), "wb") as f:
        f.write(data)
    with open(os.path.join(BUILD, exe + ".rc"), "w", newline="\r\n") as f:
        f.write('1 24 "%s.exe.manifest"\n' % exe)     # CREATEPROCESS_MANIFEST_RESOURCE_ID, RT_MANIFEST
    res = os.path.join(BUILD, exe + ".res")
    r = subprocess.run([RC, "/r", "/fo", res, exe + ".rc"], cwd=BUILD, capture_output=True, text=True)
    if r.returncode != 0:
        print("RC failed:", r.stdout, r.stderr)
        return None
    return res


def ensure_data_link():
    """data/ -> ref/warzone2100/data (a junction: no admin rights needed)."""
    link = os.path.join(ROOT, "data")
    target = os.path.join(REF, "data")
    if os.path.exists(link) or not os.path.isdir(target):
        return
    r = subprocess.run(["cmd", "/c", "mklink", "/J", link, target], capture_output=True, text=True)
    if r.returncode == 0:
        print("data: junction made to %s" % os.path.relpath(target, ROOT))
    else:
        print("WARNING: could not make the data junction (%s); run with --datadir=%s" % (r.stdout.strip() or r.stderr.strip(), target))


def main(argv):
    release = "--release" in argv
    if "--break-compat" in argv:
        victim = argv[argv.index("--break-compat") + 1]
        path = os.path.join(COMPAT, victim + ".dll")
        if os.path.exists(dll_path(victim)):
            # the rebuild registers new GUIDs; drop the old ones first, or they stay in the registry
            subprocess.run(["regsvr32", "/u", "/s", dll_path(victim)])
        if os.path.exists(path):
            os.remove(path)
            print("dropped compat/%s.dll: %s gets new GUIDs" % (victim, victim))
    for d in (BIN, COMPAT, BUILD):
        os.makedirs(d, exist_ok=True)
    write_autorevision()
    ensure_data_link()

    built = []
    for name, kind, sub, refs in PROJECTS:
        folder = os.path.join(SRC, sub)
        if not sources(folder):
            print("%s: no sources in src/%s, skipped" % (name, sub))
            continue
        refs = [r for r in refs if r in built]
        resfile = None
        if kind == "exe":
            resfile = write_manifest([r for r in built])
            if resfile is None:
                return 1
        vbp = write_vbp(name, kind, folder, refs, release, resfile)
        if not make(name, folder, vbp):
            return 1
        built.append(name)
        if kind == "dll":
            compat_dll = os.path.join(COMPAT, name + ".dll")
            if not os.path.exists(compat_dll):
                shutil.copy(dll_path(name), COMPAT)
                print("%s: compat/%s.dll made (binary compatibility from now on)" % (name, name))
            else:
                # An interface that grew gets a new type library version, and until the compat copy
                # has the new members VB gives them (and new enums) fresh GUIDs on every build, which
                # breaks the projects built against the last ones: refresh the copy.
                new_version = typelib.library(dll_path(name))[2]
                old_version = typelib.library(compat_dll)[2]
                if new_version != old_version:
                    shutil.copy(dll_path(name), COMPAT)
                    print("%s: compat/%s.dll updated, %d.%d -> %d.%d (its interface grew)"
                          % (name, name, old_version[0], old_version[1], new_version[0], new_version[1]))

    if "--unregister" in argv:
        for name, kind, _, _ in PROJECTS:
            if kind == "dll" and os.path.exists(dll_path(name)):
                r = subprocess.run(["regsvr32", "/u", "/s", dll_path(name)])
                print("unregistered %s.dll (exit %d)" % (name, r.returncode))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
